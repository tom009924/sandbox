package com.example.todo.mbt

import tools.jackson.databind.JsonNode
import tools.jackson.databind.ObjectMapper
import java.io.File

data class ItfTodoState(
    val completed: Boolean,
    val subtasks: Set<String>,
)

data class ItfTraceStep(
    val index: Int,
    val maxActiveTodos: Int,
    val todos: Map<String, ItfTodoState>,
    val lastAction: String,
    val lastStatus: Int,
    val lastTargetId: String,
    val lastSubtaskId: String,
    val lastKey: String,
    val lastFingerprint: String,
    val lastCompleted: Boolean,
) {
    fun activeTodoCount(): Int = todos.values.count { !it.completed }
}

data class QuintItfTrace(
    val source: String,
    val steps: List<ItfTraceStep>,
)

/**
 * Loads standard Informal Trace Format (ITF) JSON files generated by Quint / Apalache.
 * Format specification: https://apalache-mc.org/docs/adr/015adr-trace.html
 */
object QuintItfTraceLoader {
    fun load(path: String, objectMapper: ObjectMapper = ObjectMapper()): QuintItfTrace {
        val file = File(path)
        require(file.exists()) { "ITF trace file not found: $path" }
        val root = objectMapper.readTree(file)
        val source = root.path("#meta").path("source").asString("")
        val statesNode = root.path("states")
        require(statesNode.isArray && statesNode.size() > 0) {
            "ITF trace '$path' must contain a non-empty 'states' array"
        }

        val steps = (0 until statesNode.size()).map { i -> parseState(statesNode.get(i), i) }
        return QuintItfTrace(source = source, steps = steps)
    }

    private fun parseState(node: JsonNode, fallbackIndex: Int): ItfTraceStep {
        val index = node.path("#meta").path("index").asInt(fallbackIndex)
        val todos = parseTodosMap(node.path("todos"))
        return ItfTraceStep(
            index = index,
            maxActiveTodos = parseBigInt(node.path("maxActiveTodos")),
            todos = todos,
            lastAction = node.path("lastAction").asString(""),
            lastStatus = parseBigInt(node.path("lastStatus")),
            lastTargetId = node.path("lastTargetId").asString(""),
            lastSubtaskId = node.path("lastSubtaskId").asString(""),
            lastKey = node.path("lastKey").asString(""),
            lastFingerprint = node.path("lastFingerprint").asString(""),
            lastCompleted = node.path("lastCompleted").asBoolean(false),
        )
    }

    private fun parseBigInt(node: JsonNode): Int =
        if (node.has("#bigint")) {
            node.get("#bigint").asString().toInt()
        } else {
            node.asInt()
        }

    private fun parseTodosMap(node: JsonNode): Map<String, ItfTodoState> {
        val entries = node.path("#map")
        if (!entries.isArray) return emptyMap()
        val result = linkedMapOf<String, ItfTodoState>()
        for (i in 0 until entries.size()) {
            val pair = entries.get(i)
            val key = pair.get(0).asString()
            val value = pair.get(1)
            val completed = value.path("completed").asBoolean(false)
            val subtasks = parseStringSet(value.path("subtasks"))
            result[key] = ItfTodoState(completed = completed, subtasks = subtasks)
        }
        return result
    }

    private fun parseStringSet(node: JsonNode): Set<String> {
        val items = node.path("#set")
        if (!items.isArray) return emptySet()
        return (0 until items.size()).mapTo(linkedSetOf()) { items.get(it).asString() }
    }
}
